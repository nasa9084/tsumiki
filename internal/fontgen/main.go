// fontgen extracts the glyph outlines tsumiki needs to write text into PDF drawings as vector
// paths, from an OpenType font (collection), and writes them as Go source.
//
// Usage:
//
//	go run . -font NotoSansCJK-Regular.ttc -index 0 -out ../../glyphs_data.go
//
// The characters are printable ASCII, a few drawing symbols and the Japanese labels of the JIS
// drawing template. The outlines are stored in font units (1000 per em), y up.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"golang.org/x/image/font"
	"golang.org/x/image/font/sfnt"
	"golang.org/x/image/math/fixed"
)

// symbols are the non-ASCII characters drawings use; japanese are the characters of the
// template's Japanese labels.
const (
	symbols  = "×·⌀□°±"
	japanese = "図名番作成者日付尺度投影法単位第三角正面平右側等断"
)

// substitutes draws characters the font lacks with the glyph of a look-alike.
var substitutes = map[rune]rune{'⌀': '∅'}

func main() {
	fontPath := flag.String("font", "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc", "font file")
	index := flag.Int("index", 0, "font index within a collection (0: Noto Sans CJK JP)")
	out := flag.String("out", "../../glyphs_data.go", "output Go file")
	flag.Parse()
	data, err := os.ReadFile(*fontPath)
	if err != nil {
		log.Fatal(err)
	}
	f, err := load(data, *index)
	if err != nil {
		log.Fatal(err)
	}
	source, err := generate(f)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, source, 0o644); err != nil {
		log.Fatal(err)
	}
}

func load(data []byte, index int) (*sfnt.Font, error) {
	if collection, err := sfnt.ParseCollection(data); err == nil {
		return collection.Font(index)
	}
	return sfnt.Parse(data)
}

func generate(f *sfnt.Font) ([]byte, error) {
	var buffer sfnt.Buffer
	unitsPerEm := f.UnitsPerEm()
	ppem := fixed.Int26_6(unitsPerEm) << 6 // one pixel per font unit
	var runes []rune
	for r := rune(0x20); r <= 0x7e; r++ {
		runes = append(runes, r)
	}
	runes = append(runes, []rune(symbols+japanese)...)

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/fontgen from %s; DO NOT EDIT.\n\n", fontName(f, &buffer))
	out.WriteString("package tsumiki\n\n")
	out.WriteString("// glyphOutlines holds outlines in font units (1000 per em), y up: M x y, L x y, Q x1 y1 x y,\n")
	out.WriteString("// C x1 y1 x2 y2 x y and Z, separated by spaces.\n")
	out.WriteString("var glyphOutlines = map[rune]glyphOutline{\n")
	for _, r := range runes {
		source := r
		if substitute, ok := substitutes[r]; ok {
			source = substitute
		}
		glyphIndex, err := f.GlyphIndex(&buffer, source)
		if err != nil || glyphIndex == 0 {
			return nil, fmt.Errorf("the font has no glyph for %q", source)
		}
		advance, err := f.GlyphAdvance(&buffer, glyphIndex, ppem, font.HintingNone)
		if err != nil {
			return nil, err
		}
		segments, err := f.LoadGlyph(&buffer, glyphIndex, ppem, nil)
		if err != nil {
			return nil, err
		}
		scale := 1000 / float64(unitsPerEm)
		fmt.Fprintf(&out, "\t%q: {advance: %d, path: %q},\n", r, round(float64(advance)/64*scale), path(segments, scale))
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

// path writes segments as a compact path string; sfnt's y axis points down, the output's up.
func path(segments sfnt.Segments, scale float64) string {
	var sb strings.Builder
	point := func(p fixed.Point26_6) string {
		return fmt.Sprintf(" %d %d", round(float64(p.X)/64*scale), round(-float64(p.Y)/64*scale))
	}
	open := false
	for _, s := range segments {
		switch s.Op {
		case sfnt.SegmentOpMoveTo:
			if open {
				sb.WriteString(" Z ")
			}
			sb.WriteString("M" + point(s.Args[0]))
			open = true
		case sfnt.SegmentOpLineTo:
			sb.WriteString(" L" + point(s.Args[0]))
		case sfnt.SegmentOpQuadTo:
			sb.WriteString(" Q" + point(s.Args[0]) + point(s.Args[1]))
		case sfnt.SegmentOpCubeTo:
			sb.WriteString(" C" + point(s.Args[0]) + point(s.Args[1]) + point(s.Args[2]))
		}
	}
	if open {
		sb.WriteString(" Z")
	}
	return sb.String()
}

func round(x float64) int {
	if x < 0 {
		return -int(-x + 0.5)
	}
	return int(x + 0.5)
}

func fontName(f *sfnt.Font, buffer *sfnt.Buffer) string {
	name, err := f.Name(buffer, sfnt.NameIDFull)
	if err != nil {
		return "the font"
	}
	return name
}
